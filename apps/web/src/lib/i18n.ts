import { useSyncExternalStore } from 'react';

export type Locale = 'zh-CN' | 'en';

const LOCALE_KEY = 'nh-locale';
const listeners = new Set<() => void>();

/**
 * The two public domains are intentionally language-specific:
 * 360biji.com is the Chinese edition, 360note.com is the English edition.
 * Both hostnames talk to the same API and database, so accounts and content
 * are shared. Other hostnames (localhost, previews) may choose freely.
 */
function domainLocale(): Locale | null {
  if (typeof window === 'undefined') return null;
  const host = window.location.hostname.toLowerCase();
  if (host === '360note.com' || host === 'www.360note.com') return 'en';
  if (host === '360biji.com' || host === 'www.360biji.com') return 'zh-CN';
  return null;
}

function detectLocale(): Locale {
  const forced = domainLocale();
  if (forced) return forced;
  try {
    const saved = localStorage.getItem(LOCALE_KEY);
    if (saved === 'zh-CN' || saved === 'en') return saved;
  } catch {
    /* ignore */
  }
  try {
    return navigator.language.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en';
  } catch {
    return 'zh-CN';
  }
}

function applyDocumentLocale(locale: Locale): void {
  if (typeof document !== 'undefined') {
    document.documentElement.lang = locale === 'en' ? 'en' : 'zh-CN';
  }
}

let currentLocale: Locale = detectLocale();

export function getLocale(): Locale {
  return currentLocale;
}

export function setLocale(locale: Locale): void {
  currentLocale = locale;
  try {
    localStorage.setItem(LOCALE_KEY, locale);
  } catch {
    /* ignore */
  }
  applyDocumentLocale(locale);
  listeners.forEach((listener) => listener());
}

applyDocumentLocale(currentLocale);

function subscribe(listener: () => void): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

